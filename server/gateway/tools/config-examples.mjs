#!/usr/bin/env node
// Writes .env.example and gateway.config.example.json from the config schema (lib/config.mjs), so both always
// document every key, plus gateway.config.starter.json: the few keys a new install sets (copy that one, not the reference). `--check` exits 1 when the committed files are out of date (test/config.test.mjs runs it).
import fs from 'node:fs';
import path from 'node:path';
import { describe, GATEWAY_DIR } from '../lib/config.mjs';

// Example values that show the shape better than the defaults (never real hosts, people or credentials).
const EXAMPLES = {
  publicUrl: 'https://gateway.example.com', 'owner.name': 'Sam', 'owner.aliases': ['sam', 'sammy'], 'home.lat': 52.52, 'home.lon': 13.405, tz: 'Europe/Berlin', units: 'metric',
  'hermes.callUrl': 'ws://hermes:8642/v1/voice/call', 'notify.ownChats': ['my bots', 'family'],
  'homeAssistant.scenes': [{ id: 'movie', name: 'Movie time', icon: 'bulb', entity: 'scene.movie_time' }],
  'homeAssistant.alarm': { time: 'sensor.wake_time', mode: 'select.alarm_mode', times: { '7:00 AM': 'script.alarm_early', '8:30 AM': 'script.alarm_late' }, styles: ['Gentle', 'Loud'] },
  'homeAssistant.printers': [{ id: 'printer', name: '3D printer', progress: 'sensor.printer_progress', state: 'sensor.printer_print_state', online: 'binary_sensor.printer_online', entityPrefix: 'sensor.printer_' }],
  targets: [
    { id: 'local', name: 'Recordings folder', kind: 'directory', path: './recordings' },
    { id: 'notes', name: 'Notes webhook', kind: 'webhook', url: 'https://notes.example.com/hooks/glasses', auth: { type: 'hmac', secret: 'NOTES_WEBHOOK_SECRET' }, audio: 'multipart', retries: 3, backoffMs: 2000 },
    { id: 'assistant', name: 'Hermes', kind: 'hermes' },
  ],
  routes: { memo: ['local', 'assistant'], ambient: ['local'], dictation: [] },
  'people.file': './people.json', 't3.machinesFile': './t3-machines.json',
};
const shown = leaf => leaf.path in EXAMPLES ? EXAMPLES[leaf.path] : leaf.default;
const envText = v => v == null ? '' : Array.isArray(v) && v.every(x => typeof x === 'string') ? v.join(',') : typeof v === 'object' ? JSON.stringify(v) : String(v);

export function envExample() {
  const lines = ['# RayNeo iO HUD gateway: every setting as an environment variable (all optional).',
    '# gateway.config.json (GATEWAY_CONFIG) can set the same keys and is merged over these. Generated by tools/config-examples.mjs.',
    '# Secrets are never set here by value in config; the gateway reads them BY NAME from the secrets provider',
    '# (GATEWAY_SECRETS=env: an env var of that name, or NAME_FILE pointing at a file).', '',
    '# GATEWAY_CONFIG=./gateway.config.json', ''];
  let group = null;
  for (const leaf of describe()) {
    const top = leaf.path.split('.')[0];
    if (top !== group) { lines.push('', leaf.path.includes('.') ? `# ---- ${top}` : '#'); group = top; }
    lines.push(`# ${leaf.path}: ${leaf.doc}${leaf.default != null && leaf.default !== '' && !(Array.isArray(leaf.default) && !leaf.default.length) ? ` Default: ${envText(leaf.default)}.` : ''}`);
    lines.push(`# ${leaf.env}=${envText(shown(leaf))}`);
  }
  lines.push('', '# ---- secrets read by name (env provider). Set only the ones for integrations you use.',
    '# GLASSES_API_TOKEN=<long random string the phone app sends>', '# GLASSES_AGENT_TOKEN=<long random string Hermes sends (MCP, /assistant/*, /notify/hermes)>',
    '# TV_LAUNCHER_TOKEN=', '# LLM_API_KEY=', '# HERMES_API_SERVER_KEY=', '# HERMES_CALL_TOKEN=', '# BEEPER_ACCESS_TOKEN=',
    '# HOMEASSISTANT_URL=http://homeassistant.local:8123', '# HOMEASSISTANT_TOKEN=', '# COMPOSIO_MCP_URL=', '# COMPOSIO_MCP_TOKEN=', '# AUDIOBOOKSHELF_TOKEN=',
    '# OURA_ACCESS_TOKEN=', '# WEIGHTGURUS_EMAIL=', '# WEIGHTGURUS_PASSWORD=', '# NOTES_WEBHOOK_SECRET=',
    '# T3 machine tokens: the secret names listed in t3-machines.json, e.g. T3_DESKTOP_TOKEN=',
    '', '# ---- infisical provider (GATEWAY_SECRETS=infisical)',
    '# INFISICAL_URL=https://app.infisical.com', '# INFISICAL_CLIENT_ID=', '# INFISICAL_CLIENT_SECRET=', '# INFISICAL_PROJECT_ID=', '# INFISICAL_ENV=prod', '# INFISICAL_PATHS=/', '');
  return lines.join('\n');
}
export function configExample() {
  const out = { $comment: 'REFERENCE ONLY: every key with an example value (RayNeo iO HUD gateway, GATEWAY_CONFIG). Do not copy this file whole: keys in the config file override environment variables. Start from gateway.config.starter.json and add only the keys you need; see .env.example for what each does. Generated by tools/config-examples.mjs.' };
  for (const leaf of describe()) {
    const parts = leaf.path.split('.'); let o = out;
    for (const k of parts.slice(0, -1)) o = (o[k] ??= {});
    o[parts.at(-1)] = shown(leaf);
  }
  return JSON.stringify(out, null, 2) + '\n';
}

/** The starting point for config/gateway.config.json: who the glasses belong to and the assistant's name, nothing else. */
export function starterConfig() {
  return JSON.stringify({
    $comment: 'RayNeo iO HUD gateway config (GATEWAY_CONFIG). Add only the keys you need; gateway.config.example.json lists every key. Keys set here override environment variables (except port, host, dataDir and worker). Relative file paths resolve next to this file. Generated by tools/config-examples.mjs.',
    owner: { name: 'Sam', aliases: [] },
    assistant: { name: 'Hermes' },
  }, null, 2) + '\n';
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith('config-examples.mjs')) {
  const files = { '.env.example': envExample(), 'gateway.config.example.json': configExample(), 'gateway.config.starter.json': starterConfig() };
  let stale = false;
  for (const [name, text] of Object.entries(files)) {
    const file = path.join(GATEWAY_DIR, name);
    if (process.argv.includes('--check')) { if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) { console.error(`${name} is out of date: run node tools/config-examples.mjs`); stale = true; } }
    else fs.writeFileSync(file, text);
  }
  process.exitCode = stale ? 1 : 0;
}
